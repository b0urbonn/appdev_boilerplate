"""Regenerate runtime artwork from the original assets (requires Pillow)."""

import base64
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
IMAGES = ROOT / "assets/images"
FRAME_MS = 80
MASCOT_SIZE = (160, 200)
EYE_REGION = (150, 155, 280, 225)  # Source coordinates across the moving head poses.


def restore_eye_whites(frame):
    """Restore eye whites/glints removed with the original white backdrop.

    Flood only the exterior transparency away, then restore enclosed holes
    in the eye region. This follows blinking and movement without painting
    over pupils, outlines, or the transparent silhouette.
    """
    holes = frame.getchannel("A").point(lambda alpha: 255 if alpha < 250 else 0)
    ImageDraw.floodfill(holes, (0, 0), 0)
    frame.paste((255, 255, 255, 255), EYE_REGION, holes.crop(EYE_REGION))
    return frame


def optimize_mascot():
    frames = []
    timestamps = []
    elapsed = 0
    next_sample = 0
    with Image.open(IMAGES / "mascot.webp") as source:
        for index in range(source.n_frames):
            source.seek(index)
            source.load()
            duration = source.info["duration"]
            while next_sample < elapsed + duration:
                # Preserve the hard edges of the pixel artwork and avoid
                # creating extra alpha gradients for the decoder to process.
                corrected = restore_eye_whites(source.convert("RGBA"))
                frames.append(corrected.resize(MASCOT_SIZE, Image.Resampling.NEAREST))
                timestamps.append(next_sample)
                next_sample += FRAME_MS
            elapsed += duration

    durations = [min(FRAME_MS, elapsed - timestamp) for timestamp in timestamps]
    frames[0].save(
        IMAGES / "mascot-animation.webp",
        save_all=True,
        append_images=frames[1:],
        duration=durations,
        loop=0,
        background=(0, 0, 0, 0),
        quality=60,
        method=4,
        minimize_size=True,
    )
    poster = BytesIO()
    frames[0].save(poster, format="WEBP", quality=80, method=4)
    (IMAGES / "mascot-poster.webp").write_bytes(poster.getvalue())
    encoded = base64.b64encode(poster.getvalue()).decode("ascii")
    target = ROOT / "src/generated/mascotPoster.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        "// Generated by scripts/optimize-app-images.py.\n"
        "// This small first pose travels with the JS bundle, avoiding an asset request.\n"
        "export const MASCOT_POSTER = {\n"
        f"  uri: 'data:image/webp;base64,{encoded}',\n"
        f"  width: {MASCOT_SIZE[0]},\n"
        f"  height: {MASCOT_SIZE[1]},\n"
        "} as const;\n"
    )


def optimize_still(name, max_size, quality):
    with Image.open(IMAGES / f"{name}.png") as source:
        image = source.convert("RGBA")
        image.thumbnail(max_size, Image.Resampling.LANCZOS)
        image.save(IMAGES / f"{name}.webp", quality=quality, method=4)


def embed_onboarding_for_web():
    entries = []
    for name in ("welcome", "detect-deepfake", "harmful-content", "privacy"):
        path = IMAGES / f"onboarding-{name}.webp"
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        with Image.open(path) as image:
            width, height = image.size
        entries.append(
            f"  {{ uri: 'data:image/webp;base64,{encoded}', width: {width}, height: {height} }},"
        )
    (ROOT / "src/generated/onboardingImages.web.ts").write_text(
        "// Generated by scripts/optimize-app-images.py.\n"
        "// Inline small illustrations on web to avoid image request waterfalls.\n"
        "export const ONBOARDING_IMAGES = [\n" + "\n".join(entries) + "\n] as const;\n"
    )


if __name__ == "__main__":
    optimize_mascot()
    for name in ("welcome", "detect-deepfake", "harmful-content", "privacy"):
        optimize_still(f"onboarding-{name}", (480, 480), 58)
    embed_onboarding_for_web()
    optimize_still("chat-fox", (192, 192), 72)
    for name in ("mascot-animation", "mascot-poster", "chat-fox", "onboarding-welcome",
                 "onboarding-detect-deepfake", "onboarding-harmful-content", "onboarding-privacy"):
        path = IMAGES / f"{name}.webp"
        print(f"{path.relative_to(ROOT)}: {path.stat().st_size:,} bytes")
